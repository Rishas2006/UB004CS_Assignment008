-- RH Hospital Management System : PostgreSQL schema (v2) - tested design for Supabase (PostgreSQL 15+) and any PostgreSQL 13+.
-- Run it with:  npm run db:setup   (creates the tables, then loads the sample data)
-- or paste this file into the Supabase SQL Editor and run it once.
--
-- Differences from the old MySQL version:
--   * JSON -> JSONB, TINYINT(1) -> BOOLEAN, DATETIME -> TIMESTAMPTZ (always stored as UTC), AUTO_INCREMENT -> IDENTITY, CHAR(36) ids -> UUID
--   * the "slot_lock" generated column is replaced by a PARTIAL UNIQUE INDEX (appt_slot_uq): two live bookings of one slot are impossible,
--     a cancelled slot can be booked again
--   * e-mail uniqueness is case-insensitive through a unique index on lower(email)
--   * Row Level Security is switched ON for every table (last section). The API connects with the database owner role (which bypasses RLS),
--     while the public Supabase Data API (anon / authenticated keys) can read nothing. Patient data must never be exposed through it.

-- =====================================================================
-- 1. Reference data and public website content
-- =====================================================================
CREATE TABLE branches (
  id VARCHAR(30) PRIMARY KEY,
  name JSONB NOT NULL,                              -- {"en": "...", "si": "...", "ta": "..."}
  address VARCHAR(255) NOT NULL,
  phone VARCHAR(30) NOT NULL,
  lat NUMERIC(9,6),
  lng NUMERIC(9,6)
);

CREATE TABLE departments (
  id VARCHAR(30) PRIMARY KEY,
  name JSONB NOT NULL,
  description JSONB,
  icon VARCHAR(40),
  is_centre BOOLEAN NOT NULL DEFAULT false
);

CREATE TABLE services (
  slug VARCHAR(60) PRIMARY KEY,
  icon VARCHAR(40),
  name JSONB NOT NULL,
  description JSONB,
  points JSONB,
  hours VARCHAR(60)
);

CREATE TABLE lab_tests (
  code VARCHAR(20) PRIMARY KEY,
  name VARCHAR(120) NOT NULL,
  category VARCHAR(40) NOT NULL,
  price NUMERIC(10,2) NOT NULL CHECK (price >= 0),
  turnaround_hours INT NOT NULL CHECK (turnaround_hours > 0)
);

CREATE TABLE packages (
  id VARCHAR(40) PRIMARY KEY,
  icon VARCHAR(40),
  name JSONB NOT NULL,
  price NUMERIC(10,2) NOT NULL CHECK (price >= 0),
  discount NUMERIC(10,2) CHECK (discount IS NULL OR discount >= 0),
  tests JSONB                                       -- JSON array of test names
);

CREATE TABLE rooms (
  id VARCHAR(30) PRIMARY KEY,
  name JSONB NOT NULL,
  price NUMERIC(10,2) NOT NULL CHECK (price >= 0),
  description JSONB
);

CREATE TABLE faqs (
  id VARCHAR(30) PRIMARY KEY,
  category VARCHAR(40),
  question JSONB NOT NULL,
  answer JSONB NOT NULL
);

CREATE TABLE news (
  slug VARCHAR(100) PRIMARY KEY,
  published_on DATE NOT NULL,
  category JSONB,
  title JSONB NOT NULL,
  body JSONB NOT NULL,
  is_published BOOLEAN NOT NULL DEFAULT true
);

CREATE TABLE announcements (
  id VARCHAR(40) PRIMARY KEY,
  severity VARCHAR(10) NOT NULL CHECK (severity IN ('info','warning','urgent')),
  text JSONB NOT NULL,
  is_active BOOLEAN NOT NULL DEFAULT true,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE promotions (
  id VARCHAR(40) PRIMARY KEY,
  valid_until DATE NOT NULL,
  title JSONB NOT NULL,
  description JSONB,
  is_active BOOLEAN NOT NULL DEFAULT true
);

CREATE TABLE jobs (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title VARCHAR(120) NOT NULL,
  department VARCHAR(80),
  branch_id VARCHAR(30) REFERENCES branches(id),
  closing_date DATE,
  is_open BOOLEAN NOT NULL DEFAULT true
);

CREATE TABLE reviews (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  author VARCHAR(60) NOT NULL,
  rating INT NOT NULL CHECK (rating BETWEEN 1 AND 5),
  body JSONB NOT NULL,
  status VARCHAR(10) NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING','APPROVED','REJECTED')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- awards, annual reports, board directors, policies, gallery, canteen, emergency contacts
CREATE TABLE content_items (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kind VARCHAR(30) NOT NULL CHECK (kind IN ('award','report','director','policy','gallery','canteen','emergency_contact')),
  data JSONB NOT NULL,
  sort_order INT NOT NULL DEFAULT 0,
  is_published BOOLEAN NOT NULL DEFAULT true
);
CREATE INDEX content_kind_idx ON content_items (kind, sort_order);

CREATE TABLE opening_hours (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  label VARCHAR(80) NOT NULL,
  hours VARCHAR(80) NOT NULL,
  is_24x7 BOOLEAN NOT NULL DEFAULT false
);

CREATE TABLE parking_lots (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  branch_id VARCHAR(30) REFERENCES branches(id),
  name VARCHAR(80) NOT NULL,
  total INT NOT NULL CHECK (total >= 0),
  free INT NOT NULL,
  CHECK (free BETWEEN 0 AND total)
);

CREATE TABLE wards (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  branch_id VARCHAR(30) REFERENCES branches(id),
  name VARCHAR(80) NOT NULL,
  total_beds INT NOT NULL CHECK (total_beds >= 0)
);

CREATE TABLE beds (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ward_id INT NOT NULL REFERENCES wards(id) ON DELETE CASCADE,
  label VARCHAR(30) NOT NULL,
  status VARCHAR(12) NOT NULL DEFAULT 'available' CHECK (status IN ('available','occupied','cleaning','reserved')),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT beds_ward_label_uq UNIQUE (ward_id, label)
);

-- =====================================================================
-- 2. Identity and security   (UUID primary keys are generated by the application)
-- =====================================================================
CREATE TABLE users (
  id UUID PRIMARY KEY,
  name VARCHAR(80) NOT NULL,
  email VARCHAR(120) NOT NULL,
  phone VARCHAR(30),
  password_hash VARCHAR(100) NOT NULL,
  role VARCHAR(20) NOT NULL DEFAULT 'patient' CHECK (role IN
    ('patient','doctor','nurse','reception','pharmacy','laboratory','hr','finance','ambulance','branch-admin','super-admin')),
  branch_id VARCHAR(30) REFERENCES branches(id),
  is_verified BOOLEAN NOT NULL DEFAULT false,
  is_active BOOLEAN NOT NULL DEFAULT true,
  failed_logins INT NOT NULL DEFAULT 0,
  locked_until TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX users_email_uq ON users (lower(email));

CREATE TABLE otp_codes (
  id UUID PRIMARY KEY,
  user_id UUID NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  code_hash VARCHAR(100) NOT NULL,
  purpose VARCHAR(10) NOT NULL DEFAULT 'verify' CHECK (purpose IN ('verify','reset')),
  attempts INT NOT NULL DEFAULT 0,
  used BOOLEAN NOT NULL DEFAULT false,
  expires_at TIMESTAMPTZ NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX otp_user_idx ON otp_codes (user_id, purpose, used);

CREATE TABLE refresh_tokens (
  id UUID PRIMARY KEY,
  user_id UUID NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  token_hash CHAR(64) NOT NULL,
  expires_at TIMESTAMPTZ NOT NULL,
  revoked BOOLEAN NOT NULL DEFAULT false,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT refresh_hash_uq UNIQUE (token_hash)
);

CREATE TABLE audit_logs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id UUID REFERENCES users(id) ON DELETE SET NULL,
  action VARCHAR(60) NOT NULL,
  entity VARCHAR(40),
  entity_id VARCHAR(60),
  ip VARCHAR(60),
  meta JSONB,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX audit_created_idx ON audit_logs (created_at);

-- =====================================================================
-- 3. Clinical: patients, doctors, appointments, prescriptions, lab
-- =====================================================================
CREATE TABLE patients (
  id UUID PRIMARY KEY,
  user_id UUID REFERENCES users(id) ON DELETE CASCADE,
  mrn VARCHAR(20) NOT NULL,                         -- medical record number, e.g. RH-000123
  dob DATE,
  gender VARCHAR(10) CHECK (gender IS NULL OR gender IN ('male','female','other')),
  nic VARCHAR(20),
  address VARCHAR(255),
  blood_group VARCHAR(3) CHECK (blood_group IS NULL OR blood_group IN ('A+','A-','B+','B-','AB+','AB-','O+','O-')),
  allergies VARCHAR(300),
  emergency_contact VARCHAR(120),
  qr_token VARCHAR(64) NOT NULL,                    -- random token printed in the QR health card
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT patients_user_uq UNIQUE (user_id),
  CONSTRAINT patients_mrn_uq UNIQUE (mrn),
  CONSTRAINT patients_qr_uq UNIQUE (qr_token)
);

CREATE TABLE doctors (
  id VARCHAR(20) PRIMARY KEY,
  user_id UUID REFERENCES users(id) ON DELETE SET NULL,
  name VARCHAR(100) NOT NULL,
  initials VARCHAR(10),
  dept_id VARCHAR(30) NOT NULL REFERENCES departments(id),
  branch_id VARCHAR(30) NOT NULL REFERENCES branches(id),
  experience_years INT NOT NULL DEFAULT 0,
  languages JSONB,                                  -- e.g. ["en","si"]
  video_enabled BOOLEAN NOT NULL DEFAULT false,
  is_resident BOOLEAN NOT NULL DEFAULT false,
  fee NUMERIC(10,2) NOT NULL CHECK (fee >= 0),
  schedule_text VARCHAR(80),
  slmc_no VARCHAR(30),
  is_active BOOLEAN NOT NULL DEFAULT true,
  CONSTRAINT doctors_user_uq UNIQUE (user_id)
);

CREATE TABLE doctor_schedules (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  doctor_id VARCHAR(20) NOT NULL REFERENCES doctors(id) ON DELETE CASCADE,
  weekday INT NOT NULL CHECK (weekday BETWEEN 0 AND 6),     -- 0 = Sunday
  start_time TIME NOT NULL,
  end_time TIME NOT NULL,
  slot_minutes INT NOT NULL DEFAULT 15 CHECK (slot_minutes BETWEEN 5 AND 60),
  CHECK (end_time > start_time),
  CONSTRAINT sched_uq UNIQUE (doctor_id, weekday, start_time)
);

CREATE TABLE appointments (
  id UUID PRIMARY KEY,
  ref VARCHAR(20) NOT NULL,                         -- RH-123456
  patient_id UUID REFERENCES patients(id),
  guest_name VARCHAR(80),
  guest_phone VARCHAR(30),
  doctor_id VARCHAR(20) NOT NULL REFERENCES doctors(id),
  branch_id VARCHAR(30) NOT NULL REFERENCES branches(id),
  appt_date DATE NOT NULL,
  appt_time TIME NOT NULL,
  type VARCHAR(10) NOT NULL DEFAULT 'IN_PERSON' CHECK (type IN ('IN_PERSON','VIDEO')),
  reason VARCHAR(500),
  status VARCHAR(12) NOT NULL DEFAULT 'CONFIRMED' CHECK (status IN
    ('PENDING','CONFIRMED','CHECKED_IN','IN_CONSULT','COMPLETED','CANCELLED','NO_SHOW')),
  token_no INT,
  video_room VARCHAR(40),
  checked_in_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CHECK (patient_id IS NOT NULL OR (guest_name IS NOT NULL AND guest_phone IS NOT NULL)),
  CONSTRAINT appt_ref_uq UNIQUE (ref)
);
-- No double booking: a PARTIAL unique index ignores cancelled rows, so a cancelled slot can be booked again.
CREATE UNIQUE INDEX appt_slot_uq ON appointments (doctor_id, appt_date, appt_time) WHERE status <> 'CANCELLED';
CREATE INDEX appt_patient_idx ON appointments (patient_id);
CREATE INDEX appt_day_idx ON appointments (branch_id, appt_date);

CREATE TABLE prescriptions (
  id UUID PRIMARY KEY,
  ref VARCHAR(20) NOT NULL,                         -- P-10420
  appointment_id UUID REFERENCES appointments(id) ON DELETE SET NULL,
  patient_id UUID NOT NULL REFERENCES patients(id),
  doctor_id VARCHAR(20) NOT NULL REFERENCES doctors(id),
  notes VARCHAR(1000),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT rx_ref_uq UNIQUE (ref)
);

CREATE TABLE prescription_items (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  prescription_id UUID NOT NULL REFERENCES prescriptions(id) ON DELETE CASCADE,
  drug VARCHAR(100) NOT NULL,
  dose VARCHAR(50) NOT NULL,
  frequency VARCHAR(50) NOT NULL,
  days INT NOT NULL CHECK (days BETWEEN 1 AND 365)
);

CREATE TABLE lab_orders (
  id UUID PRIMARY KEY,
  ref VARCHAR(20) NOT NULL,                         -- L-20011
  patient_id UUID NOT NULL REFERENCES patients(id),
  test_code VARCHAR(20) NOT NULL REFERENCES lab_tests(code),
  ordered_by VARCHAR(20) REFERENCES doctors(id),
  status VARCHAR(20) NOT NULL DEFAULT 'ORDERED' CHECK (status IN ('ORDERED','SAMPLE_COLLECTED','PROCESSING','COMPLETED','CANCELLED')),
  result_text VARCHAR(2000),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  resulted_at TIMESTAMPTZ,
  CONSTRAINT lab_ref_uq UNIQUE (ref)
);

-- =====================================================================
-- 4. Billing and payments (PayHere)
-- =====================================================================
CREATE TABLE invoices (
  id UUID PRIMARY KEY,
  ref VARCHAR(20) NOT NULL,                         -- INV-100045
  patient_id UUID NOT NULL REFERENCES patients(id),
  appointment_id UUID REFERENCES appointments(id) ON DELETE SET NULL,
  description VARCHAR(200) NOT NULL,
  amount NUMERIC(10,2) NOT NULL CHECK (amount > 0),
  status VARCHAR(10) NOT NULL DEFAULT 'UNPAID' CHECK (status IN ('UNPAID','PAID','FAILED','REFUNDED')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT inv_ref_uq UNIQUE (ref)
);

CREATE TABLE payments (
  id UUID PRIMARY KEY,
  invoice_id UUID NOT NULL REFERENCES invoices(id),
  gateway VARCHAR(20) NOT NULL DEFAULT 'payhere',
  order_id VARCHAR(60) NOT NULL,
  gateway_payment_id VARCHAR(60),
  amount NUMERIC(10,2) NOT NULL,
  currency CHAR(3) NOT NULL DEFAULT 'LKR',
  status_code INT,                                  -- 2 success, 0 pending, -1 cancelled, -2 failed, -3 chargedback
  status VARCHAR(12) NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING','SUCCESS','FAILED','CANCELLED','CHARGEBACK')),
  raw JSONB,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT pay_order_uq UNIQUE (order_id)
);

-- =====================================================================
-- 5. Pharmacy, ambulance, rooms, public requests
-- =====================================================================
CREATE TABLE pharmacy_items (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sku VARCHAR(30) NOT NULL,
  name VARCHAR(100) NOT NULL,
  stock INT NOT NULL DEFAULT 0 CHECK (stock >= 0),
  reorder_level INT NOT NULL DEFAULT 20,
  price NUMERIC(10,2) NOT NULL CHECK (price >= 0),
  expiry DATE,
  CONSTRAINT pharm_sku_uq UNIQUE (sku)
);

CREATE TABLE pharmacy_orders (
  id UUID PRIMARY KEY,
  ref VARCHAR(20) NOT NULL,                         -- PH-30010
  patient_id UUID REFERENCES patients(id),
  prescription_ref VARCHAR(20) REFERENCES prescriptions(ref),
  mode VARCHAR(10) NOT NULL CHECK (mode IN ('pickup','delivery')),
  address VARCHAR(250),
  status VARCHAR(20) NOT NULL DEFAULT 'RECEIVED' CHECK (status IN ('RECEIVED','PREPARING','READY','OUT_FOR_DELIVERY','DELIVERED','CANCELLED')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CHECK (mode = 'pickup' OR address IS NOT NULL),
  CONSTRAINT pho_ref_uq UNIQUE (ref)
);

CREATE TABLE ambulance_vehicles (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  plate VARCHAR(20) NOT NULL,
  branch_id VARCHAR(30) REFERENCES branches(id),
  status VARCHAR(10) NOT NULL DEFAULT 'AVAILABLE' CHECK (status IN ('AVAILABLE','BUSY','OFFLINE')),
  lat NUMERIC(9,6),
  lng NUMERIC(9,6),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT veh_plate_uq UNIQUE (plate)
);

CREATE TABLE ambulance_requests (
  id UUID PRIMARY KEY,
  ref VARCHAR(20) NOT NULL,                         -- AMB-50010
  caller_name VARCHAR(80) NOT NULL,
  phone VARCHAR(30) NOT NULL,
  address VARCHAR(250) NOT NULL,
  lat NUMERIC(9,6),
  lng NUMERIC(9,6),
  notes VARCHAR(500),
  vehicle_id INT REFERENCES ambulance_vehicles(id),
  status VARCHAR(15) NOT NULL DEFAULT 'REQUESTED' CHECK (status IN ('REQUESTED','DISPATCHED','ON_SCENE','TRANSPORTING','ARRIVED','CLOSED','CANCELLED')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT amb_ref_uq UNIQUE (ref)
);

CREATE TABLE room_bookings (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  room_id VARCHAR(30) NOT NULL REFERENCES rooms(id),
  patient_id UUID REFERENCES patients(id),
  name VARCHAR(80) NOT NULL,
  phone VARCHAR(30) NOT NULL,
  from_date DATE NOT NULL,
  to_date DATE NOT NULL,
  status VARCHAR(10) NOT NULL DEFAULT 'REQUESTED' CHECK (status IN ('REQUESTED','CONFIRMED','CANCELLED')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CHECK (to_date >= from_date)
);

CREATE TABLE contact_messages (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(80) NOT NULL,
  email VARCHAR(120),
  phone VARCHAR(30),
  subject VARCHAR(120),
  message TEXT NOT NULL,
  status VARCHAR(10) NOT NULL DEFAULT 'NEW' CHECK (status IN ('NEW','READ','REPLIED')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE job_applications (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  job_id INT REFERENCES jobs(id) ON DELETE SET NULL,
  name VARCHAR(80) NOT NULL,
  email VARCHAR(120) NOT NULL,
  phone VARCHAR(30) NOT NULL,
  cover_note TEXT,
  cv_url VARCHAR(300),
  status VARCHAR(12) NOT NULL DEFAULT 'RECEIVED' CHECK (status IN ('RECEIVED','SHORTLISTED','REJECTED','HIRED')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE notifications (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id UUID REFERENCES users(id) ON DELETE CASCADE,
  channel VARCHAR(10) NOT NULL DEFAULT 'email' CHECK (channel IN ('email','sms','push')),
  subject VARCHAR(200),
  body TEXT,
  status VARCHAR(10) NOT NULL DEFAULT 'SENT',
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- =====================================================================
-- 6. HR and payroll
-- =====================================================================
CREATE TABLE staff (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id UUID NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  branch_id VARCHAR(30) REFERENCES branches(id),
  job_title VARCHAR(80) NOT NULL,
  basic_salary NUMERIC(10,2) NOT NULL CHECK (basic_salary >= 0),
  allowances NUMERIC(10,2) NOT NULL DEFAULT 0,
  join_date DATE NOT NULL DEFAULT CURRENT_DATE,
  CONSTRAINT staff_user_uq UNIQUE (user_id)
);

CREATE TABLE leaves (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  staff_id INT NOT NULL REFERENCES staff(id) ON DELETE CASCADE,
  type VARCHAR(10) NOT NULL CHECK (type IN ('annual','sick','casual','unpaid')),
  from_date DATE NOT NULL,
  to_date DATE NOT NULL,
  reason VARCHAR(300),
  status VARCHAR(10) NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING','APPROVED','REJECTED')),
  decided_by UUID REFERENCES users(id),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CHECK (to_date >= from_date)
);

CREATE TABLE advances (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  staff_id INT NOT NULL REFERENCES staff(id) ON DELETE CASCADE,
  amount NUMERIC(10,2) NOT NULL CHECK (amount > 0),
  reason VARCHAR(300),
  deduct_month CHAR(7) NOT NULL,                    -- YYYY-MM
  status VARCHAR(10) NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING','APPROVED','REJECTED','DEDUCTED')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE payroll (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  staff_id INT NOT NULL REFERENCES staff(id) ON DELETE CASCADE,
  month CHAR(7) NOT NULL,                           -- YYYY-MM
  basic NUMERIC(10,2) NOT NULL,
  allowances NUMERIC(10,2) NOT NULL DEFAULT 0,
  epf_employee NUMERIC(10,2) NOT NULL DEFAULT 0,    -- 8% of basic
  epf_employer NUMERIC(10,2) NOT NULL DEFAULT 0,    -- 12% of basic
  etf_employer NUMERIC(10,2) NOT NULL DEFAULT 0,    -- 3% of basic
  unpaid_leave_deduction NUMERIC(10,2) NOT NULL DEFAULT 0,
  advance_deduction NUMERIC(10,2) NOT NULL DEFAULT 0,
  net NUMERIC(10,2) NOT NULL,
  status VARCHAR(10) NOT NULL DEFAULT 'GENERATED' CHECK (status IN ('GENERATED','PAID')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT payroll_month_uq UNIQUE (staff_id, month)
);

